        private const string CliName = "lis-ultrawide-fix.exe";
        private const string CliWhere = "in the cli folder next to this program";

        /// <summary>The installer: in the cli folder next to this program (the
        /// archive's layout), else next to it (a build tree); null when neither.</summary>
        private static string CliPath()
        {
            string here = AppDomain.CurrentDomain.BaseDirectory;
            foreach (string dir in new string[] { Path.Combine(here, "cli"), here })
            {
                string p = Path.Combine(dir, CliName);
                if (File.Exists(p)) return p;
            }
            return null;
        }

        /// <summary>Start settings shared by every run of the installer.</summary>
        //
        // The encodings matter: the installer writes UTF-8 to a pipe, and this
        // process must read the same, or a game path with a non-ASCII
        // character in it arrives as mojibake. Both streams are always
        // redirected: .NET refuses to start a process that carries an encoding
        // for a stream it is not capturing.
        private static ProcessStartInfo Launch(string cli, string args)
        {
            ProcessStartInfo psi = new ProcessStartInfo(cli, args);
            psi.UseShellExecute = false;
            psi.CreateNoWindow = true;
            psi.RedirectStandardOutput = true;
            psi.RedirectStandardError = true;
            psi.StandardOutputEncoding = new UTF8Encoding(false);
            psi.StandardErrorEncoding = new UTF8Encoding(false);
            psi.WorkingDirectory = Path.GetDirectoryName(cli);
            return psi;
        }

        private static string Quote(string s)
        {
            return "\"" + s + "\"";
        }

        /// <summary>Run the installer to completion, out of sight; its output, or null.</summary>
        private static string RunCli(string args)
        {
            string cli = CliPath();
            if (cli == null) return null;
            try
            {
                using (Process p = Process.Start(Launch(cli, args)))
                {
                    // drained on its own thread: a long complaint on stderr
                    // would otherwise fill its pipe and hang while we read
                    // the other one
                    Process capture = p;
                    ThreadPool.QueueUserWorkItem(delegate
                    {
                        try { capture.StandardError.ReadToEnd(); }
                        catch { }
                    });
                    string text = p.StandardOutput.ReadToEnd();
                    p.WaitForExit();
                    return text;
                }
            }
            catch { return null; }
        }

        /// <summary>The tab-separated fields of a "known:" or "found:" line, or null when there are not n of them.</summary>
        private static string[] Fields(string line, string prefix, int n)
        {
            string[] f = line.Substring(prefix.Length).Split('\t');
            return f.Length == n ? f : null;
        }

        private void AutoDetect()
        {
            // executable: the installer's own search, so the window agrees
            // with what Install would do; the games it knows come along
            if (CliPath() == null)
            {
                Log(CliName + " must be " + CliWhere + ". Unpack the whole archive.");
            }
            else
            {
                List<string> notes = new List<string>();
                string text = RunCli("find") ?? "";
                foreach (string line in text.Split('\n'))
                {
                    string t = line.Trim();
                    string[] f;
                    if (t.StartsWith("known: ") && (f = Fields(t, "known: ", 3)) != null)
                    {
                        GameInfo g = new GameInfo();
                        g.Title = f[0];
                        g.Short = f[1];
                        g.Exe = f[2];
                        known.Add(g);
                    }
                    else if (t.StartsWith("found: ") && (f = Fields(t, "found: ", 4)) != null)
                    {
                        ExeItem item = new ExeItem();
                        item.Title = f[0];
                        item.Short = f[1];
                        item.Path = f[2];
                        item.Source = f[3];
                        found.Add(item);
                    }
                    else if (t.StartsWith("Note: ")) notes.Add(t);
                }
                if (found.Count > 1)
                {
                    // several games, or copies of one: the list, the installer's
                    // pick selected
                    UsePicker();
                    foreach (ExeItem item in found) cmbExe.Items.Add(item);
                    FitDropDown();
                    foreach (ExeItem item in found) Log("Found " + item.Short + " via " + item.Source + ".");
                    Log("Pick one to fix. Each is fixed on its own: install once for each.");
                    foreach (string n in notes) Log(n);
                    cmbExe.SelectedIndex = 0;
                }
                else if (found.Count == 1)
                {
                    txtExePath.Text = found[0].Path;
                    Log("Found " + found[0].Short + " via " + found[0].Source + ".");
                }
                else
                {
                    Log("Could not find the game automatically - use Browse.");
                }
            }
            SetGameTitle(picker ? null : Describe(ExePath).Title);
            UpdateExeHeader();

            // resolution: select the preset matching this display, else Custom
            Rectangle b = Screen.PrimaryScreen.Bounds;
            txtWidth.Text = b.Width.ToString();
            txtHeight.Text = b.Height.ToString();
            int match = -1;
            for (int i = 0; i < presets.Count; i++)
                if (presets[i].W == b.Width && presets[i].H == b.Height) { match = i; break; }
            cmbPresets.SelectedIndex = (match >= 0) ? match : presets.Count;
            Log(string.Format("Detected display: {0}x{1}{2}", b.Width, b.Height,
                              match >= 0 ? "" : "  (using Custom)"));

            // show the start of the path rather than opening mid-selection
            txtExePath.SelectionLength = 0;
            txtExePath.SelectionStart = 0;
            ActiveControl = btnInstall;
        }

        // ---- status badges ------------------------------------------------
        // Whether the fix's loader is next to the executable, what it reported
        // at the last launch, and whether the UI container is current, is
        // decided by "lis-ultrawide-fix status". Keeping the answer there
        // means the badges can never disagree with what Install would do.

        private const string GlyphOk = "✔";      // heavy check mark
        private const string GlyphWarn = "⚠";    // warning sign
        private static readonly Color OkColor = Color.FromArgb(0, 128, 0);
        private static readonly Color WarnColor = Color.FromArgb(190, 100, 0);

        private int checkToken;

        private void SetExeStatus(string glyph, Color color, string text, string tip)
        {
            lblExeStatus.ForeColor = color;
            lblExeStatus.Text = (glyph.Length > 0 ? glyph + "  " : "") + text;
            tips.SetToolTip(lblExeStatus, tip ?? text);
        }

        private void SetFilesStatus(string glyph, Color color, string text, string tip)
        {
            lblFilesStatus.ForeColor = color;
            lblFilesStatus.Text = text.Length == 0
                ? "" : (glyph.Length > 0 ? glyph + "  " : "") + text;
            tips.SetToolTip(lblFilesStatus, tip ?? text);
        }

        private void OnExePathChanged(object sender, EventArgs e)
        {
            tips.SetToolTip(txtExePath, txtExePath.Text.Trim());
            checkTimer.Stop();
            checkTimer.Start();          // coalesce typing into one check
        }

        private void OnCheckTick(object sender, EventArgs e)
        {
            checkTimer.Stop();
            StartExeCheck();
        }

        private void StartExeCheck()
        {
            if (!IsHandleCreated) return;
            string path = ExePath;
            int token = ++checkToken;

            if (path.Length == 0)
            {
                SetExeStatus("", SystemColors.GrayText, "No executable selected.", null);
                SetFilesStatus("", SystemColors.GrayText, "", null);
                SetGameTitle(null);
                return;
            }
            if (!File.Exists(path))
            {
                SetExeStatus(GlyphWarn, WarnColor, "There is no file at that path.", path);
                SetFilesStatus("", SystemColors.GrayText, "", null);
                SetGameTitle(null);
                return;
            }
            SetExeStatus("", SystemColors.GrayText,
                         "Checking " + Path.GetFileName(path) + "...", path);
            SetFilesStatus("", SystemColors.GrayText, "", null);

            ThreadPool.QueueUserWorkItem(delegate
            {
                string title, status, detail, files, filesDetail;
                RunCheck(path, out title, out status, out detail, out files, out filesDetail);
                if (token != checkToken) return;             // superseded
                try
                {
                    BeginInvoke((MethodInvoker)delegate
                    {
                        if (token != checkToken) return;
                        ApplyStatus(status, detail, title);
                        ApplyFilesStatus(files, filesDetail);
                    });
                }
                catch { }                                    // form already gone
            });
        }

        /// <summary>The full-width UI container: is it there, and is it current?</summary>
        private void ApplyFilesStatus(string status, string detail)
        {
            switch (status)
            {
                case "current":
                    SetFilesStatus(GlyphOk, OkColor, "Full-width UI " + detail + ".", detail);
                    break;
                case "stale":
                    SetFilesStatus(GlyphWarn, WarnColor,
                                   "Full-width UI was built for a different build of the "
                                   + "game - Install again before playing.", detail);
                    break;
                case "unrecorded":
                case "incomplete":
                    SetFilesStatus(GlyphWarn, WarnColor,
                                   "Full-width UI needs installing again.", detail);
                    break;
                case "none":
                    SetFilesStatus("", SystemColors.GrayText,
                                   "Full-width UI is not installed.", detail);
                    break;
                default:
                    SetFilesStatus("", SystemColors.GrayText, "", detail);
                    break;
            }
        }

        /// <summary>The installer's one-line detail as a sentence of its own.</summary>
        private static string Sentence(string detail)
        {
            if (string.IsNullOrEmpty(detail)) return null;
            string s = char.ToUpper(detail[0]) + detail.Substring(1);
            return s.EndsWith(".") ? s : s + ".";
        }

        private void ApplyStatus(string status, string detail, string title)
        {
            // the title is the installer's word on which game this is; it
            // means nothing for a file no game claims
            bool isGame = status == "installed" || status == "outdated"
                          || status == "foreign" || status == "none";
            SetGameTitle(isGame ? title : null);
            switch (status)
            {
                case "installed":
                    if (detail != null && detail.Contains("not applied"))
                        SetExeStatus(GlyphWarn, WarnColor,
                                     "Loader installed, but the game did not take the fix at "
                                     + "the last launch - see LiSUltrawideCamera.log.", detail);
                    else
                        SetExeStatus(GlyphOk, OkColor, "Ultrawide camera loader installed.", detail);
                    break;
                case "outdated":
                    SetExeStatus(GlyphWarn, WarnColor,
                                 "A different version of the loader is installed - Install "
                                 + "updates it.", detail);
                    break;
                case "foreign":
                    SetExeStatus(GlyphWarn, WarnColor,
                                 "Another program's winhttp.dll is next to the game - the fix "
                                 + "will not replace it.", detail);
                    break;
                case "none":
                    SetExeStatus("", SystemColors.GrayText,
                                 "Ultrawide camera loader is not installed.", detail);
                    break;
                case "notgame":
                    // the installer names every executable it knows
                    SetExeStatus(GlyphWarn, WarnColor,
                                 Sentence(detail) ?? "That is not the game's executable.", detail);
                    break;
                case "missing":
                    SetExeStatus(GlyphWarn, WarnColor, "There is no file at that path.", detail);
                    break;
                case "nocli":
                    SetExeStatus("", SystemColors.GrayText,
                                 "Not checked - " + CliName + " is not " + CliWhere + ".", null);
                    break;
                default:
                    SetExeStatus("", SystemColors.GrayText, "Could not check this file.", detail);
                    break;
            }
        }

        /// <summary>"lis-ultrawide-fix status", out of sight; never prompts.</summary>
        private void RunCheck(string path, out string title, out string status, out string detail,
                              out string files, out string filesDetail)
        {
            title = null;
            status = "error";
            detail = null;
            files = "error";
            filesDetail = null;
            if (CliPath() == null) { status = "nocli"; return; }
            string text = RunCli("status --exe " + Quote(path));
            if (text == null) return;
            foreach (string line in text.Split('\n'))
            {
                string t = line.Trim();
                if (t.StartsWith("title: ")) title = t.Substring(7).Trim();
                else if (t.StartsWith("status: ")) status = t.Substring(8).Trim();
                else if (t.StartsWith("detail: ")) detail = t.Substring(8).Trim();
                else if (t.StartsWith("files: ")) files = t.Substring(7).Trim();
                else if (t.StartsWith("filesdetail: ")) filesDetail = t.Substring(13).Trim();
            }
        }

        protected override void OnShown(EventArgs e)
        {
            base.OnShown(e);
            StartExeCheck();
        }

        // ---- running Install and Restore ----------------------------------

        private void Run(string args)
        {
            string cli = CliPath();
            if (cli == null)
            {
                MessageBox.Show(CliName + " must be " + CliWhere + ". Unpack the "
                                + "whole archive, not just this file.",
                                "Missing " + CliName, MessageBoxButtons.OK,
                                MessageBoxIcon.Error);
                return;
            }

            btnInstall.Enabled = btnRestore.Enabled = false;
            txtLog.Clear();
            Log("> " + cli + " " + args);
            Log("");

            bool denied = false;          // was it a permissions refusal?
            Process proc = new Process();
            proc.StartInfo = Launch(cli, args);
            proc.EnableRaisingEvents = true;
            DataReceivedEventHandler onLine = delegate(object s, DataReceivedEventArgs e)
            {
                if (e.Data == null) return;
                // the installer ends that advice this way ("run this
                // installer as administrator")
                if (e.Data.IndexOf("as administrator",
                                   StringComparison.OrdinalIgnoreCase) >= 0)
                    denied = true;
                Log(e.Data);
            };
            proc.OutputDataReceived += onLine;
            proc.ErrorDataReceived += onLine;
            proc.Exited += delegate
            {
                int code = proc.ExitCode;
                BeginInvoke((MethodInvoker)delegate
                {
                    Log("");
                    Log(code == 0 ? "Finished." : "Failed (exit code " + code + ").");
                    btnInstall.Enabled = btnRestore.Enabled = true;
                    StartExeCheck();           // what is installed just changed
                    if (code != 0 && denied) OfferElevation(cli, args);
                });
            };
            try
            {
                proc.Start();
                proc.BeginOutputReadLine();
                proc.BeginErrorReadLine();
            }
            catch (Exception ex)
            {
                Log("Could not start " + cli + ": " + ex.Message);
                btnInstall.Enabled = btnRestore.Enabled = true;
            }
        }

        // A game under Program Files - Steam's default - cannot be written by an
        // ordinary process, and "right-click, Run as administrator" is not
        // something this program can assume anyone knows. So it offers, and
        // repeats the exact same command with the elevation prompt attached.
        private void OfferElevation(string cli, string args)
        {
            if (MessageBox.Show(
                    "Windows refused permission to write the game files.\r\n\r\n"
                    + "This happens when the game is installed under Program "
                    + "Files. Run the same install again as administrator?",
                    "Administrator rights needed", MessageBoxButtons.YesNo,
                    MessageBoxIcon.Question) != DialogResult.Yes)
                return;
            RunElevated(cli, args);
        }

        /// <summary>The same command, elevated, with its output in a file.</summary>
        //
        // An elevated child cannot have its pipes redirected (that needs
        // UseShellExecute = false, which in turn cannot request elevation), so
        // it is run through cmd with its output sent to a temporary file, which
        // is poured into the log when it finishes.
        private void RunElevated(string cli, string args)
        {
            string log = Path.Combine(Path.GetTempPath(), "lisde-elevated.log");
            try { if (File.Exists(log)) File.Delete(log); }
            catch { }

            // Elevation can land in a different account - a standard user who
            // types an administrator's password gets that administrator's
            // profile - and then %LOCALAPPDATA% is the wrong one: Engine.ini
            // would be written where the game will never read it. It is the
            // invoking user's, so pass theirs through.
            string local = Environment.GetFolderPath(
                Environment.SpecialFolder.LocalApplicationData);
            string keepLocal = string.IsNullOrEmpty(local)
                ? "" : "set \"LOCALAPPDATA=" + local + "\"&& ";
            string command = keepLocal + Quote(cli) + " " + args
                             + " > " + Quote(log) + " 2>&1";
            ProcessStartInfo psi = new ProcessStartInfo("cmd.exe", "/c \"" + command + "\"");
            psi.UseShellExecute = true;          // required for the elevation verb
            psi.Verb = "runas";
            psi.WindowStyle = ProcessWindowStyle.Hidden;
            psi.WorkingDirectory = Path.GetDirectoryName(cli);

            btnInstall.Enabled = btnRestore.Enabled = false;
            Log("");
            Log("Running as administrator - the output appears when it finishes.");
            Process proc;
            try
            {
                proc = Process.Start(psi);
            }
            catch (Exception ex)
            {
                // 1223 is the user dismissing the UAC prompt: not an error
                Log(ex is System.ComponentModel.Win32Exception
                    && ((System.ComponentModel.Win32Exception)ex).NativeErrorCode == 1223
                    ? "Cancelled - nothing was changed."
                    : "Could not start it as administrator: " + ex.Message);
                btnInstall.Enabled = btnRestore.Enabled = true;
                return;
            }
            proc.EnableRaisingEvents = true;
            proc.Exited += delegate
            {
                int code = proc.ExitCode;
                string text = "";
                try
                {
                    if (File.Exists(log))
                        text = File.ReadAllText(log, new UTF8Encoding(false));
                }
                catch (Exception ex) { text = "(could not read the output: " + ex.Message + ")"; }
                BeginInvoke((MethodInvoker)delegate
                {
                    foreach (string line in text.Replace("\r\n", "\n").Split('\n'))
                        if (line.Length > 0) Log(line);
                    Log("");
                    Log(code == 0 ? "Finished." : "Failed (exit code " + code + ").");
                    btnInstall.Enabled = btnRestore.Enabled = true;
                    StartExeCheck();
                    try { if (File.Exists(log)) File.Delete(log); }
                    catch { }
                });
            };
        }

        /// <summary>The arguments both buttons share, or null when the form is not ready.</summary>
        private string CommonArgs()
        {
            string exe = ExePath;
            if (exe.Length == 0)
            {
                MessageBox.Show("Select the game executable first.", "No executable",
                                MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return null;
            }
            int w, h;
            if (!int.TryParse(txtWidth.Text.Trim(), out w) ||
                !int.TryParse(txtHeight.Text.Trim(), out h) || w <= 0 || h <= 0)
            {
                MessageBox.Show("Enter a valid resolution.", "Invalid resolution",
                                MessageBoxButtons.OK, MessageBoxIcon.Warning);
                return null;
            }
            return "--exe " + Quote(exe) + " --width " + w
                   + " --height " + h + " --yes";
        }

        private void OnInstall(object sender, EventArgs e)
        {
            string common = CommonArgs();
            if (common == null) return;
            if (!chkExe.Checked && !chkGameFiles.Checked &&
                !chkChromatic.Checked && !chkSharpen.Checked)
            {
                MessageBox.Show("Nothing is selected.", "Nothing to do",
                                MessageBoxButtons.OK, MessageBoxIcon.Information);
                return;
            }
            string args = "install " + common;
            if (!chkExe.Checked) args += " --no-camera";
            if (!chkGameFiles.Checked) args += " --no-ui";
            if (!chkChromatic.Checked) args += " --no-chromatic-fix";
            if (chkSharpen.Checked) args += " --sharpen";
            Run(args);
        }

        private void OnRestore(object sender, EventArgs e)
        {
            string common = CommonArgs();
            if (common == null) return;
            Run("restore " + common);
        }

        [STAThread]
        public static void Main()
        {
            // Must happen BEFORE any window exists - doing it later makes Windows
            // re-map an already-created form and shrink it by the DPI factor.
            try { SetProcessDPIAware(); }
            catch { }
            Application.EnableVisualStyles();
            Application.SetCompatibleTextRenderingDefault(false);
            Application.Run(new MainForm());
        }
