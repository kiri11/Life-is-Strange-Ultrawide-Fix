        /// <summary>Swap the path box for the list of games. Once; never back.</summary>
        private void UsePicker()
        {
            if (picker) return;
            picker = true;
            exeRow.Controls.Remove(txtExePath);
            exeRow.Controls.Add(cmbExe, 0, 0);
